const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {matches} = require('../docs/translations/search.js');
const text = fs.readFileSync(path.join(__dirname, '../docs/translations/books.json'), 'utf8');
const {books} = JSON.parse(text);
assert.equal(new Set(books.map(b => b.id)).size, books.length);
assert.equal(books.filter(b => b.translation).length, 58);
assert.equal(books.filter(b => b.chineseEdition).length, 6);
assert.equal(books.filter(b => b.ownedChineseEdition).length, 5);
for (const term of ['privateEvidence', 'currentFile', 'PROGRESS.json', 'github.com', 'token', '机构']) assert(!text.includes(term));
const find = (query, filter='all') => books.filter(b => matches(b,query,filter));
assert.equal(find('Rudin 数学分析原理', 'mine').length, 1);
assert.equal(find('Principles of Mathematical Analysis').length, 1);
assert.equal(find('GTM 005').length, 1);
assert.equal(find('GTM 005')[0].author, 'Mac Lane');
assert.equal(find('GTM-5')[0].author, 'Mac Lane');
assert.equal(find('GTM5').length, 1);
assert.equal(find('Hartshorne', 'chinese').length, 1);
assert.equal(find('Munkres', 'mine').length, 0);
assert.equal(find('Munkres', 'chinese').length, 1);
assert.equal(find('Lee Smooth')[0].id, 'GTM-218');
assert(find('Lee Smooth')[0].chineseEdition.manuscript);
assert(find('GTM 275')[0].translation.progress.includes('未覆盖原书全本'));
assert.equal(find('zzzz-unlisted-book').length, 0);
assert.equal(find('<script>alert(1)</script>').length, 0);
assert(find('費曼').length === 0 || find('費曼').every(b => b.ownedChineseEdition));
console.log('Translation lookup checks passed: bilingual title, author, GTM aliases, filters, evidence boundaries');
